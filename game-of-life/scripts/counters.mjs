// For each formation a player might switch to, find the bot formations that beat it
// most reliably under the shipped rules; the bot's counter-audible picks from these.
//   node scripts/counters.mjs [seedsPerPair]    -> writes src/engine/counters.js
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { writeFileSync } from 'node:fs';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { FREE_BUILDS } from '../src/engine/library.js';
import { placeFormation } from '../src/engine/formations.js';
import { createEngine } from '../src/engine/engine.js';
import { DEFAULT_FORTUNE_RULES } from '../src/engine/fortuneRules.js';
import { BLUE, RED } from '../src/engine/constants.js';

const ME = fileURLToPath(import.meta.url);
const K = Number(process.argv[2] || 2);
const TOP = 3;

if (!isMainThread) {
  const byId = new Map(FREE_BUILDS.map((b) => [b.id, b]));
  const out = [];
  for (const [p, b, seed] of workerData.tasks) {
    const e = createEngine({ seed, fortune: DEFAULT_FORTUNE_RULES });
    e.loadTeams([...placeFormation(byId.get(p), BLUE), ...placeFormation(byId.get(b), RED)]);
    const o = e.runToEnd().outcome; // from the player's (Blue's) side
    out.push([p, b, o === 'lose' ? 1 : o === 'push' ? 0.5 : 0]); // 1 = the bot won
  }
  parentPort.postMessage(out);
} else {
  const ids = FREE_BUILDS.map((b) => b.id);
  const tasks = [];
  let seed = 1;
  for (const p of ids) for (const b of ids) if (p !== b) for (let k = 0; k < K; k++) tasks.push([p, b, seed++]);
  const n = Math.min(os.cpus().length, 8);
  const slices = Array.from({ length: n }, () => []);
  tasks.forEach((t, i) => slices[i % n].push(t));
  const res = (await Promise.all(slices.map((s) => new Promise((ok, no) => {
    const w = new Worker(ME, { workerData: { tasks: s } });
    w.on('message', ok); w.on('error', no);
  })))).flat();
  const score = new Map();
  for (const [p, b, v] of res) {
    const k = `${p}|${b}`;
    const e = score.get(k) || { s: 0, n: 0 };
    e.s += v; e.n++;
    score.set(k, e);
  }
  const counters = {};
  for (const p of ids) {
    counters[p] = ids.filter((b) => b !== p)
      .map((b) => ({ b, r: score.get(`${p}|${b}`).s / score.get(`${p}|${b}`).n }))
      .sort((x, y) => y.r - x.r || (x.b < y.b ? -1 : 1))
      .slice(0, TOP).map((x) => x.b);
  }
  const body = Object.entries(counters).map(([k, v]) => `  '${k}': [${v.map((x) => `'${x}'`).join(', ')}],`).join('\n');
  writeFileSync(new URL('../src/engine/counters.js', import.meta.url),
    `// Generated by scripts/counters.mjs - do not edit by hand.\n// For each formation the player might switch to: the bot formations that beat it most reliably.\nexport const COUNTERS = {\n${body}\n};\n`);
  console.log(`wrote counters for ${ids.length} formations from ${tasks.length} matches`);
}
