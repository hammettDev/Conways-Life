// Put every candidate back in the roster.
import { writeFileSync } from 'node:fs';
import { CANDIDATES } from '../src/engine/library.js';

const args = process.argv.slice(2);
const jsonAt = args.indexOf('--json');
const jsonOut = jsonAt >= 0 ? args[jsonAt + 1] : null;
const only = args.filter((a, i) => !a.startsWith('--') && i !== jsonAt + 1); // optional sports to include
const ids = CANDIDATES.filter((b) => !only.length || only.includes(b.sport)).map((b) => `'${b.id}'`);
if (jsonOut) {
  writeFileSync(jsonOut, JSON.stringify({ free: ids.map((i) => i.replace(/'/g, '')), tutorial: [], boss: [] }));
  console.log(ids.length, 'builds written to', jsonOut);
  process.exit(0);
}
writeFileSync(new URL('../src/engine/roster.js', import.meta.url),
  `// Generated by scripts/cull.mjs - do not edit by hand.\nexport const ROSTER = {\n  free: [${ids.join(', ')}],\n  tutorial: [],\n  boss: [],\n};\n`);
console.log(ids.length, 'builds in roster');
