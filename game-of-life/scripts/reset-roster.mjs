// Put every candidate back in the roster (free builds + all weapons).
import { writeFileSync } from 'node:fs';
import { CANDIDATES } from '../src/engine/library.js';

const ids = (f) => '[' + CANDIDATES.filter(f).map((b) => `'${b.id}'`).join(', ') + ']';
writeFileSync(new URL('../src/engine/roster.js', import.meta.url),
  `// Generated by scripts/cull.mjs - do not edit by hand.\nexport const ROSTER = {\n  free: ${ids((b) => b.sport !== 'arsenal')},\n  premium: [],\n  arsenal: ${ids((b) => b.sport === 'arsenal')},\n};\n`);
