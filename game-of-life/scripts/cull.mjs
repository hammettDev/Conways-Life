// Settle the roster: retire weak free builds, move strong ones to the priced
// tier, drop weak weapons, and repeat until nothing moves.
//   node scripts/cull.mjs [maxRounds]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ROSTER } from '../src/engine/roster.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const tmpRoster = '/tmp/cull-roster.json';
const tmpOut = '/tmp/cull-ratings.json';
const LOW = 0.40;       // below this a free build is retired
const HIGH = 0.58;      // above this a free build must be paid for
const PREMIUM_MAX = 0.75; // stronger than this is too swingy even when priced
const WEAPON_MIN = 0.60;
const rounds = Number(process.argv[2] || 30);
const STEP = Number(process.argv[3] || 3); // outliers handled per round

let roster = { free: [...ROSTER.free], premium: [...ROSTER.premium], arsenal: [...ROSTER.arsenal] };
const retired = [];

for (let round = 1; round <= rounds; round++) {
  writeFileSync(tmpRoster, JSON.stringify(roster));
  execFileSync('node', [root + 'scripts/balance.mjs', '--frozen', '--quiet', '--roster', tmpRoster, '--json', tmpOut], { stdio: 'inherit' });
  const r = JSON.parse(readFileSync(tmpOut, 'utf8'));

  // Only the worst few outliers move each round, so the pool re-settles
  // between cuts instead of cascading.
  const outliers = [...roster.free, ...roster.premium]
    .map((id) => ({ id, rate: r[id], dist: r[id] < LOW ? LOW - r[id] : r[id] > HIGH ? r[id] - HIGH : 0 }))
    .filter((o) => o.dist > 0 || roster.premium.includes(o.id))
    .sort((a, b) => b.dist - a.dist);
  const toMove = new Set(outliers.slice(0, STEP).map((o) => o.id));
  const next = { free: [], premium: [], arsenal: [] };
  let moved = 0;
  for (const id of [...roster.free, ...roster.premium]) {
    const rate = r[id];
    const wasFree = roster.free.includes(id);
    if (toMove.has(id) && (rate < LOW || rate > PREMIUM_MAX)) { retired.push(id); moved++; }
    else if (rate > HIGH) { next.premium.push(id); if (wasFree && toMove.has(id)) moved++; else if (wasFree) next.premium.pop(), next.free.push(id); }
    else { next.free.push(id); if (!wasFree) moved++; }
  }
  for (const id of roster.arsenal) {
    if (r[id] >= WEAPON_MIN) next.arsenal.push(id);
    else { retired.push(id); moved++; }
  }
  console.log(`round ${round}: free ${next.free.length}, premium ${next.premium.length}, weapons ${next.arsenal.length}, moved ${moved}`);
  roster = next;
  if (moved === 0) break;
}

const fmt = (a) => '[' + a.map((i) => `'${i}'`).join(', ') + ']';
writeFileSync(root + 'src/engine/roster.js',
  `// Generated by scripts/cull.mjs - do not edit by hand.\nexport const ROSTER = {\n  free: ${fmt(roster.free)},\n  premium: ${fmt(roster.premium)},\n  arsenal: ${fmt(roster.arsenal)},\n};\n`);
console.log('retired:', retired.join(' '));
