// Settle the roster by retiring builds whose score against the pool is too
// far from even. Only the worst few go each round so the pool re-settles
// between cuts.   node scripts/cull.mjs [maxRounds] [perRound] [low] [high]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ROSTER } from '../src/engine/roster.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const tmpRoster = '/tmp/cull-roster.json';
const tmpOut = '/tmp/cull-ratings.json';
const rounds = Number(process.argv[2] || 30);
const STEP = Number(process.argv[3] || 3);
const LOW = Number(process.argv[4] || 0.42);
const HIGH = Number(process.argv[5] || 0.58);

let free = [...ROSTER.free];
const retired = [];

for (let round = 1; round <= rounds; round++) {
  writeFileSync(tmpRoster, JSON.stringify({ free }));
  execFileSync('node', [root + 'scripts/balance.mjs', '--frozen', '--quiet', '--roster', tmpRoster, '--json', tmpOut], { stdio: 'inherit' });
  const r = JSON.parse(readFileSync(tmpOut, 'utf8'));
  const outliers = free
    .map((id) => ({ id, rate: r[id], dist: r[id] < LOW ? LOW - r[id] : r[id] > HIGH ? r[id] - HIGH : 0 }))
    .filter((o) => o.dist > 0)
    .sort((a, b) => b.dist - a.dist)
    .slice(0, STEP);
  console.log(`round ${round}: ${free.length} builds, ${outliers.length} out of band`
    + (outliers.length ? ` -> retiring ${outliers.map((o) => `${o.id} (${(o.rate * 100).toFixed(0)}%)`).join(', ')}` : ''));
  if (!outliers.length) break;
  const drop = new Set(outliers.map((o) => o.id));
  retired.push(...drop);
  free = free.filter((id) => !drop.has(id));
}

writeFileSync(root + 'src/engine/roster.js',
  `// Generated by scripts/cull.mjs - do not edit by hand.\nexport const ROSTER = {\n  free: [${free.map((i) => `'${i}'`).join(', ')}],\n};\n`);
console.log(`kept ${free.length}; retired: ${retired.join(' ') || 'none'}`);
