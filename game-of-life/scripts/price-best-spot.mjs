// Price each shop piece by what it adds at its BEST spot, not at a random one.   node scripts/price-best-spot.mjs [--write]
// A piece's value depends heavily on where it is dropped (a sandbag in the right gap took a formation from
// 59% to 92%), and a player only has to find the good spot once. So for each piece and a few formations we
// scan the drop spots, take the best on one set of seeds, re-measure it on seeds the scan never saw (so the
// pick does not flatter itself), and price the piece at PRICE_SCALE dollars per full point of win rate.
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { writeFileSync } from 'node:fs';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { FREE_BUILDS } from '../src/engine/library.js';
import { placeFormation } from '../src/engine/formations.js';
import { createEngine } from '../src/engine/engine.js';
import { DEFAULT_FORTUNE_RULES } from '../src/engine/fortuneRules.js';
import { OBJECT_CATALOG, MIN_PRICE, getObject, cellsWithObject, placementOk } from '../src/engine/objects.js';
import { BLUE, RED } from '../src/engine/constants.js';

const ME = fileURLToPath(import.meta.url);
const SEEDS = { A: [401, 402], B: [501, 502, 503, 504, 505, 506] };
const FORMATIONS = ['fb-bunch', 'fb-flexbone', 'fb-cover-3', 'fb-singleback'];
const PRICE_SCALE = 10000;
const PRICE_STEP = 25;

if (!isMainThread) {
  const out = [];
  for (const [key, id, pieceId, drop, seedSet] of workerData.tasks) {
    const f = FREE_BUILDS.find((b) => b.id === id);
    const mine = drop ? cellsWithObject(f, BLUE, getObject(pieceId), drop) : placeFormation(f, BLUE);
    let w = 0; let n = 0;
    for (const opp of FREE_BUILDS) for (const seed of SEEDS[seedSet]) {
      const e = createEngine({ seed, fortune: DEFAULT_FORTUNE_RULES });
      e.loadTeams([...mine, ...placeFormation(opp, RED, { flip: seed % 2 === 0 })]);
      const r = e.runToEnd(); w += r.outcome === 'win' ? 1 : r.outcome === 'push' ? 0.5 : 0; n++;
    }
    out.push([key, w / n]);
  }
  parentPort.postMessage(out);
} else {
  const W = Math.min(os.cpus().length, 8);
  const run = async (tasks) => {
    const slices = Array.from({ length: W }, () => []);
    tasks.forEach((t, i) => slices[i % W].push(t));
    const parts = await Promise.all(slices.map((s) => new Promise((ok, no) => { const w = new Worker(ME, { workerData: { tasks: s } }); w.on('message', ok); w.on('error', no); })));
    return new Map(parts.flat());
  };
  const pieces = OBJECT_CATALOG.map((o) => o.id);
  const builds = FORMATIONS.map((id) => FREE_BUILDS.find((b) => b.id === id)).filter(Boolean);

  // phase 1: the no-piece baseline on both seed sets, and every drop spot on seed set A
  const t1 = [];
  for (const b of builds) { t1.push([`base|A|${b.id}`, b.id, 'block', null, 'A']); t1.push([`base|B|${b.id}`, b.id, 'block', null, 'B']); }
  const spots = new Map();
  for (const p of pieces) for (const b of builds) {
    const list = [];
    for (let depth = 2; depth <= 20; depth += 3) for (let lat = -18; lat <= 18; lat += 4) if (placementOk(b, getObject(p), { depth, lat })) list.push({ depth, lat });
    spots.set(`${p}|${b.id}`, list);
    list.forEach((d, i) => t1.push([`scan|${p}|${b.id}|${i}`, b.id, p, d, 'A']));
  }
  console.log(`scanning ${t1.length} setups...`);
  const r1 = await run(t1);

  // phase 2: re-measure each best spot on the unseen seeds
  const best = new Map();
  const t2 = [];
  for (const p of pieces) for (const b of builds) {
    const list = spots.get(`${p}|${b.id}`);
    let bi = 0; let bv = -1;
    list.forEach((d, i) => { const v = r1.get(`scan|${p}|${b.id}|${i}`); if (v > bv) { bv = v; bi = i; } });
    best.set(`${p}|${b.id}`, { drop: list[bi], scan: bv });
    t2.push([`held|${p}|${b.id}`, b.id, p, list[bi], 'B']);
  }
  const r2 = await run(t2);

  const prices = {};
  console.log('piece      best-spot gain (held-out), by formation          -> price');
  for (const p of pieces) {
    const gains = builds.map((b) => r2.get(`held|${p}|${b.id}`) - r1.get(`base|B|${b.id}`));
    const gain = gains.reduce((a, c) => a + c, 0) / gains.length;
    prices[p] = Math.max(MIN_PRICE, Math.round((gain * PRICE_SCALE) / PRICE_STEP) * PRICE_STEP);
    console.log(`${p.padEnd(10)} ${gains.map((g) => `${(g * 100).toFixed(0)}%`.padStart(5)).join(' ')}   mean ${(gain * 100).toFixed(0)}%  -> $${prices[p]}`);
  }
  if (process.argv.includes('--write')) {
    const body = Object.entries(prices).map(([k, v]) => `  '${k}': ${v},`).join('\n');
    writeFileSync(new URL('../src/engine/objectPrices.js', import.meta.url), `// Generated by scripts/price-best-spot.mjs - do not edit by hand.\n// Each piece is priced by what it adds at its best spot, not at a random one.\nexport const OBJECT_PRICES = {\n${body}\n};\n`);
    console.log('wrote objectPrices.js');
  }
}
