// Level the free pool: weak builds get more bench, strong builds lose bench.
// Usage: node scripts/tune.mjs [rounds]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const benchFile = root + 'src/engine/bench.js';
const out = process.env.TUNE_TMP || '/tmp/tune-ratings.json';
const rounds = Number(process.argv[2] || 8);
const LOW = 0.46;
const HIGH = 0.54;
const MAX = 5;

const readBench = () => {
  const m = readFileSync(benchFile, 'utf8').match(/BENCH = (\{[\s\S]*?\});/);
  return JSON.parse(m[1].replace(/'/g, '"').replace(/,\s*\}/, '}'));
};
const writeBench = (b) => {
  const body = Object.keys(b).sort().map((k) => `  '${k}': ${b[k]},`).join('\n');
  writeFileSync(benchFile, `// Generated by scripts/tune.mjs - do not edit by hand.\nexport const BENCH = {\n${body}\n};\n`);
};

let bench = readBench();
for (let round = 1; round <= rounds; round++) {
  execFileSync('node', [root + 'scripts/balance.mjs', '--frozen', '--json', out], { stdio: 'ignore' });
  const rates = JSON.parse(readFileSync(out, 'utf8'));
  const free = Object.keys(rates).filter((id) => !id.startsWith('ar-'));
  let moved = 0;
  let inBand = 0;
  for (const id of free) {
    const r = rates[id];
    const n = bench[id] ?? 2;
    let next = n;
    if (r < LOW) next = Math.min(MAX, n + (r < 0.3 ? 2 : 1));
    else if (r > HIGH) next = Math.max(0, n - (r > 0.7 ? 2 : 1));
    if (next !== n) moved++;
    if (r >= LOW && r <= HIGH) inBand++;
    bench[id] = next;
  }
  const mean = free.reduce((a, id) => a + rates[id], 0) / free.length;
  console.log(`round ${round}: ${inBand}/${free.length} in band, ${moved} adjusted, mean ${mean.toFixed(3)}`);
  writeBench(bench);
  if (moved === 0) break;
}
