// Price each purchasable object by what it adds to a random build's score.
// A win-probability gain of d on an even-money bet is worth 2 * d * wager.
//   node scripts/price-objects.mjs [trials] [--write]
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { writeFileSync } from 'node:fs';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { BASE_BUILDS } from '../src/engine/library.js';
import { OBJECT_CATALOG, MIN_PRICE, placeObject } from '../src/engine/objects.js';
import { placeFormation, validateDraft } from '../src/engine/formations.js';
import { createEngine } from '../src/engine/engine.js';
import { createRng } from '../src/engine/rng.js';
import { BLUE, RED, WAGER } from '../src/engine/constants.js';

const ME = fileURLToPath(import.meta.url);
const flag = (f) => process.argv.includes(f);

if (!isMainThread) {
  const out = [];
  for (const [blue, red, seed] of workerData.tasks) {
    const e = createEngine({ seed, freezeUnderworld: true });
    e.loadTeams([...blue, ...red]);
    const r = e.runToEnd();
    out.push(r.outcome === 'win' ? 1 : r.outcome === 'push' ? 0.5 : 0);
  }
  parentPort.postMessage(out);
} else {
  const trials = Number(process.argv.slice(2).find((a) => /^\d+$/.test(a)) || 200);
  const rng = createRng(777);
  const pick = (a) => a[Math.floor(rng() * a.length)];
  const nWorkers = Math.min(os.cpus().length, 8);

  const evaluate = async (tasks) => {
    const slices = Array.from({ length: nWorkers }, () => []);
    tasks.forEach((t, i) => slices[i % nWorkers].push([i, t]));
    const parts = await Promise.all(slices.map((s) => new Promise((res, rej) => {
      const w = new Worker(ME, { workerData: { tasks: s.map(([, t]) => t) } });
      w.on('message', (m) => res(m.map((v, k) => [s[k][0], v])));
      w.on('error', rej);
    })));
    const out = new Array(tasks.length);
    for (const [i, v] of parts.flat()) out[i] = v;
    return out;
  };

  const prices = {};
  for (const obj of OBJECT_CATALOG) {
    const tasks = [];
    for (let t = 0; t < trials; t++) {
      const a = pick(BASE_BUILDS);
      let b = pick(BASE_BUILDS);
      while (b === a) b = pick(BASE_BUILDS);
      const blue = placeFormation(a, BLUE);
      const red = placeFormation(b, RED);
      let extra = null;
      for (let tries = 0; tries < 40 && !extra; tries++) {
        const cells = placeObject(obj, BLUE, {
          depth: 3 + Math.floor(rng() * 17), lat: -17 + Math.floor(rng() * 32), flip: rng() < 0.5,
        });
        const taken = new Set(blue.map((c) => `${c.x},${c.y}`));
        // Objects are extras outside the 50-cell draft cap: check the object
        // alone sits legally on our half and does not overlap the build.
        if (validateDraft(cells, BLUE).ok && !cells.some((c) => taken.has(`${c.x},${c.y}`))) extra = cells;
      }
      if (!extra) continue;
      tasks.push([blue, red, t + 1]);              // baseline
      tasks.push([[...blue, ...extra], red, t + 1]); // with the object
    }
    const res = await evaluate(tasks);
    let gain = 0; let n = 0; let helped = 0;
    for (let i = 0; i < res.length; i += 2) {
      const d = res[i + 1] - res[i];
      gain += d; n++; if (d > 0) helped++;
    }
    const delta = gain / n;
    const price = Math.max(MIN_PRICE, Math.round((2 * delta * WAGER) / 5) * 5);
    prices[obj.id] = price;
    console.log(`${obj.id.padEnd(8)} gain ${(delta * 100).toFixed(1).padStart(6)}%  helped ${(100 * helped / n).toFixed(0)}%  -> $${price}  (${n} trials)`);
  }

  if (flag('--write')) {
    const body = Object.entries(prices).map(([k, v]) => `  '${k}': ${v},`).join('\n');
    writeFileSync(new URL('../src/engine/objectPrices.js', import.meta.url),
      `// Generated by scripts/price-objects.mjs - do not edit by hand.\nexport const OBJECT_PRICES = {\n${body}\n};\n`);
    console.log('wrote src/engine/objectPrices.js');
  }
}
